// The only "marketing" stillworks does: one line at the end of `run`, and a footer in REPORT.md.
// Nothing is sent anywhere. stillworks has no telemetry and makes no network calls except to the URL you check.

export const CLI_PROMO_URL = "https://getpublishub.com/?utm_source=gh_cli";
export const REPORT_PROMO_URL = "https://getpublishub.com/?utm_source=gh_report";
export const REPO_URL = "https://github.com/valmirjunior2109-spec/stillworks";

export const CLI_PROMO = `Want this on every AI change, with regression diffs? → ${CLI_PROMO_URL}`;

export const REPORT_FOOTER =
  `<sub>Generated by [stillworks](${REPO_URL}). Want this on every AI change, with regression diffs against your last working version? ` +
  `[Publishub](${REPORT_PROMO_URL}) is building it (early access).</sub>`;

/** Off with --no-promo or NO_PUBLISHUB_PROMO=1. */
export function shouldShowPromo(flagNoPromo: boolean | undefined, env: NodeJS.ProcessEnv = process.env): boolean {
  if (flagNoPromo) return false;
  const value = (env.NO_PUBLISHUB_PROMO ?? "").trim().toLowerCase();
  return !(value === "1" || value === "true" || value === "yes");
}
