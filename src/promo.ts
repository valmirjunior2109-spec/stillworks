// The only "marketing" stillworks does: one line at the end of `init` and of `run`/`check`, and a footer in REPORT.md.
// Nothing is sent anywhere. stillworks has no telemetry and makes no network calls except to the URL you check.
// The line depends on the result: when something broke, it says what Publishub would add; when it all passed, it
// asks for nothing more than a look. The utm_source tells the two apart on getpublishub.com.

export const CLI_PROMO_URL = "https://getpublishub.com/?utm_source=gh_cli#early-access";
export const CLI_FAIL_PROMO_URL = "https://getpublishub.com/?utm_source=gh_cli_fail#pricing";
export const INIT_PROMO_URL = "https://getpublishub.com/?utm_source=gh_init#early-access";
export const REPORT_PROMO_URL = "https://getpublishub.com/?utm_source=gh_report";
export const REPORT_FAIL_PROMO_URL = "https://getpublishub.com/?utm_source=gh_report_fail#pricing";
export const REPO_URL = "https://github.com/valmirjunior2109-spec/stillworks";

/** After a run where everything passed. */
export const CLI_PROMO = `All green. Want this checked every hour on your live app, with an alert when it breaks? → ${CLI_PROMO_URL}`;

/** After a run where something broke: the moment the bug is real. */
export const CLI_FAIL_PROMO =
  `This bug would have reached your users. Publishub will watch these flows on your live app every hour and alert you when one breaks. ` +
  `Founding Customers ($0 until launch) get them set up 1:1 by the founder → ${CLI_FAIL_PROMO_URL}`;

export const INIT_PROMO = `Rather not maintain these yourself? Publishub sets them up with you and watches your live app every hour → ${INIT_PROMO_URL}`;

export const REPORT_FOOTER =
  `<sub>Generated by [stillworks](${REPO_URL}). Want this checked every hour on your live app, with alerts and a diff against your last working version? ` +
  `[Publishub](${REPORT_PROMO_URL}) is building it (early access).</sub>`;

export const REPORT_FAIL_FOOTER =
  `<sub>Generated by [stillworks](${REPO_URL}). Bugs like this one slip through when nobody runs the journeys. ` +
  `[Publishub](${REPORT_FAIL_PROMO_URL}) will watch them on your live app every hour and alert you; Founding Customers get them set up 1:1 by the founder.</sub>`;

/** The line printed after `run` or `check`. */
export function cliPromo(failed: boolean): string {
  return failed ? CLI_FAIL_PROMO : CLI_PROMO;
}

/** Off with --no-promo or NO_PUBLISHUB_PROMO=1. */
export function shouldShowPromo(flagNoPromo: boolean | undefined, env: NodeJS.ProcessEnv = process.env): boolean {
  if (flagNoPromo) return false;
  const value = (env.NO_PUBLISHUB_PROMO ?? "").trim().toLowerCase();
  return !(value === "1" || value === "true" || value === "yes");
}
